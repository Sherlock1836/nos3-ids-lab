"""Build per-MID timing profiles from disjoint nominal fit and calibration captures."""

import argparse
import csv
from pathlib import Path

import numpy as np
from sklearn.ensemble import IsolationForest

from train import COLUMNS, export

STREAMS = {"0x18FA": "Sample", "0x18E0": "CiLab"}
CAPTURE_COLUMNS = ["timestamp", "message_id", *COLUMNS, "model_score", "decision"]
FEATURE_LIMITS = [(-8192, 8191), (0, 4999), (8, 65542), (0, 127), (1, 32)]


def load_capture(path):
    values = {mid: [] for mid in STREAMS}
    with path.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != CAPTURE_COLUMNS:
            raise ValueError(f"{path}: expected feature capture header {','.join(CAPTURE_COLUMNS)}")
        for row in reader:
            if row["message_id"] in STREAMS:
                values[row["message_id"]].append([float(row[col]) for col in COLUMNS])
    for mid, rows in values.items():
        if len(rows) < 64:
            raise ValueError(f"{path}: need at least 64 nominal feature rows for {mid}")
        matrix = np.asarray(rows, dtype=np.float64)
        lower, upper = np.asarray(FEATURE_LIMITS).T
        if (not np.isfinite(matrix).all() or not np.equal(matrix, np.floor(matrix)).all()
                or (matrix < lower).any() or (matrix > upper).any()):
            raise ValueError(f"{path}: {mid} has values outside the flight feature ranges")
        values[mid] = matrix.astype(np.float32)
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fit", type=Path)
    parser.add_argument("calibration", type=Path)
    parser.add_argument("output", type=Path, help="Directory for the generated C headers")
    parser.add_argument("--reference", type=Path, help="Write full-precision calibration scores for parity checks")
    args = parser.parse_args()

    try:
        if args.fit.samefile(args.calibration) or args.fit.read_bytes() == args.calibration.read_bytes():
            raise ValueError("fit and calibration must use separate nominal captures")
        fit, calibration = load_capture(args.fit), load_capture(args.calibration)
    except (OSError, TypeError, ValueError) as error:
        parser.error(str(error))

    profiles = {}
    for mid, name in STREAMS.items():
        forest = IsolationForest(n_estimators=12, max_samples=64, random_state=42)
        forest.fit(fit[mid])
        if not any(tree.tree_.node_count > 1 for tree in forest.estimators_):
            parser.error(f"{mid}: the fit capture has no feature variation")
        samples = calibration[mid]
        scores = -forest.score_samples(samples)
        threshold = float(np.quantile(scores, 0.95, method="higher"))
        # Require corroboration outside the observed nominal range, with two NOS3 ticks
        # of margin. The score threshold itself uses only the calibration capture.
        fast_edge = min(fit[mid][:, 1].min(), samples[:, 1].min())
        short_gap = max(0, int(fast_edge) - 20)
        busy_count = int(np.quantile(samples[:, 4], 0.90, method="higher"))
        # One spare slot above the nominal maximum tolerates normal batching.
        ceiling = int(max(fit[mid][:, 4].max(), samples[:, 4].max())) + 1
        if ceiling >= 32:
            parser.error(f"{mid}: calibration saturates the detector's 32-command history")
        profiles[mid] = (name, forest, scores, threshold, short_gap, busy_count, ceiling)

    args.output.mkdir(parents=True, exist_ok=True)
    header = [
        "/* Generated by tools/train_profiles.py from separate nominal captures. */",
        "#ifndef IDS_PROFILES_H",
        "#define IDS_PROFILES_H",
        '#include "ids_detector.h"',
    ]
    references = []
    for mid, (name, forest, scores, threshold, short_gap, busy_count, ceiling) in profiles.items():
        filename = f"ids_{name.lower()}_model.h"
        prefix = f"IDS_{name}_"
        export(forest, threshold, args.output / filename, prefix=prefix, guard=f"IDS_{name.upper()}_MODEL_H")
        header.extend([
            f'#include "{filename}"',
            f"static const IDS_Profile IDS_{name}Profile = {{",
            f"    {prefix}ModelScore, {prefix}MODEL_THRESHOLD, {short_gap}, {busy_count}, {ceiling}",
            "};",
        ])
        references.extend([(mid, *row, score) for row, score in zip(calibration[mid], scores, strict=True)])
        print(f"{mid} fit/calibration {len(fit[mid])}/{len(calibration[mid])} | "
              f"threshold {threshold:.6f} | fast gap <{short_gap} ms | busy >={busy_count}/s | ceiling {ceiling}/s")
    (args.output / "ids_profiles.h").write_text("\n".join([*header, "#endif", ""]), encoding="ascii")
    if args.reference:
        with args.reference.open("w", newline="", encoding="ascii") as stream:
            csv.writer(stream).writerows(references)


if __name__ == "__main__":
    main()
